fn check(from: u32, to: u32, src: [f64; 2], want: [f64; 2], worst: &mut f64) {
    let t = Transformer::new(from, to).expect("transformer");
    let got = t.transform(src).expect("transform");
    let err = (got[0] - want[0]).hypot(got[1] - want[1]);
    *worst = worst.max(err);
    assert!(err <= MM, "EPSG:{from}->{to} {src:?} -> {got:?}, gdaltransform {want:?}, error {err:.6} m");
}

/// 경위도 → 5186·5187·5179·3857, 한반도 11곳.
#[test]
fn lonlat_to_korean_crs_matches_gdaltransform_within_1_mm() {
    let mut worst = 0.0_f64;
    for (to, table) in [(5186, TO_5186), (5187, TO_5187), (5179, TO_5179), (3857, TO_3857)] {
        for (src, want) in LONLAT.iter().zip(table) {
            check(4326, to, *src, want, &mut worst);
        }
    }
    eprintln!("4326 -> projected: max error {worst:.9} m");
}

/// 투영 좌표계 사이(5186 ↔ 5187 ↔ 5179, Bessel 5174 → 5186 측지계 변환 포함).
#[test]
fn projected_pairs_match_gdaltransform_within_1_mm() {
    let mut worst = 0.0_f64;
    for (from, to, src, want) in PAIRS {
        check(from, to, src, want, &mut worst);
    }
    eprintln!("projected pairs: max error {worst:.9} m");
}

/// proj.db 파일이 어디에도 없어도(빈 `PROJ_DATA` 폴더) 실행 파일 안의 proj.db 로 변환한다 — OSGeo4W 없는
/// PC. 환경 변수가 다른 시험과 섞이지 않게 이 시험 파일을 자식 프로세스로 다시 돌린다.
#[test]
fn embedded_proj_db_works_without_any_proj_data_folder() {
    let empty = tempfile::tempdir().expect("temp dir");
    let out = std::process::Command::new(std::env::current_exe().expect("test exe"))
        .args(["--exact", "crs::tests::projected_pairs_match_gdaltransform_within_1_mm", "--nocapture"])
        .env("PROJ_DATA", empty.path())
        .env("PROJ_DEBUG", "3")
        .output()
        .expect("run child");
    let stderr = String::from_utf8_lossy(&out.stderr);
    let stdout = String::from_utf8_lossy(&out.stdout);
    assert!(out.status.success(), "child failed:\n{stdout}\n{stderr}");
    assert!(stdout.contains("1 passed"), "child did not run the test:\n{stdout}");
    assert!(stderr.contains("proj.db) - failed"), "PROJ found a proj.db file instead:\n{stderr}");
}

/// 같은 변환기로 여러 점을 한 번에.
#[test]
fn transform_all_keeps_order() {
    let t = Transformer::new(4326, 5186).expect("transformer");
    let got = t.transform_all(&LONLAT).expect("all");
    for (g, w) in got.iter().zip(TO_5186) {
        assert!((g[0] - w[0]).hypot(g[1] - w[1]) <= MM);
    }
    assert!(Transformer::new(4326, 999_999).is_err(), "unknown EPSG code");
}
